# eval/retrieval_eval.py
"""Retrieval evaluation: dense only vs hybrid (dense + keyword, fused with RRF).

For each of the 200 HotpotQA questions, both configurations retrieve the top 10 chunks.
Their document titles are scored against the question's gold titles (supporting facts),
and every metric is averaged over the questions.

Run from the repo root:
    python -m eval.retrieval_eval --limit 10    # quick check: prints the table, saves nothing
    python -m eval.retrieval_eval               # all questions, local database -> eval/results/retrieval.md
"""
import argparse
import json
import os
import sys
import time
from datetime import date
from pathlib import Path

parser = argparse.ArgumentParser(description="Compare dense-only and hybrid retrieval.")
parser.add_argument("env_file", nargs="?", help="default .env (local); .env.neon for Neon")
parser.add_argument("--limit", type=int, help="only the first N questions; prints the table without saving it")
args = parser.parse_args()

# config.py reads ENV_FILE at import time, so it must be set before importing app.
if args.env_file:
    if not Path(args.env_file).is_file():
        sys.exit(f"Env file not found: {args.env_file}")
    os.environ["ENV_FILE"] = args.env_file

from app import db  # noqa: E402
from app.search import (  # noqa: E402
    CANDIDATES, DENSE_WEIGHT, KEYWORD_WEIGHT, RRF_K, dense_search, hybrid_search,
)
from eval.metrics import mrr, recall_at_k  # noqa: E402

QUESTIONS_PATH = Path("eval/retrieval_questions.jsonl")
RESULTS_PATH = Path("eval/results/retrieval.md")
TOP_K = 10
RECALL_KS = (2, 5, 10)  # most questions have 2 gold titles, so Recall@2 = 1.0 means a perfect top 2
CONFIGS = {
    "dense only": dense_search,
    "hybrid (dense + keyword, RRF)": hybrid_search,
}


def load_questions(limit: int | None) -> list[dict]:
    with QUESTIONS_PATH.open(encoding="utf-8") as f:
        questions = [json.loads(line) for line in f if line.strip()]
    return questions[:limit] if limit else questions


def evaluate(conn, search, questions: list[dict]) -> dict[str, float]:
    """Run one search function on every question and average each metric."""
    totals = {f"Recall@{k}": 0.0 for k in RECALL_KS}
    totals[f"MRR@{TOP_K}"] = 0.0
    seconds = 0.0
    for q in questions:
        start = time.perf_counter()
        rows = search(conn, q["question"], TOP_K)
        seconds += time.perf_counter() - start

        titles = [row["document_title"] for row in rows]
        for k in RECALL_KS:
            totals[f"Recall@{k}"] += recall_at_k(titles, q["gold_titles"], k)
        totals[f"MRR@{TOP_K}"] += mrr(titles, q["gold_titles"])

    n = len(questions)
    averages = {name: total / n for name, total in totals.items()}
    averages["ms / query"] = 1000 * seconds / n
    return averages


def to_markdown(results: dict[str, dict[str, float]], n: int, database: str) -> str:
    columns = list(next(iter(results.values())))
    lines = [
        "# Retrieval evaluation: dense only vs hybrid",
        "",
        f"{n} HotpotQA validation questions (seed 42, `{QUESTIONS_PATH.as_posix()}`), database from `{database}`, "
        f"top {TOP_K} chunks per question. A question's gold set is its supporting-fact titles (usually 2), "
        "matched against each retrieved chunk's document title. Every metric is the average over the questions.",
        "",
        "| Configuration | " + " | ".join(columns) + " |",
        "| --- | " + " | ".join("---:" for _ in columns) + " |",
    ]
    for name, metrics in results.items():
        cells = [f"{value:.0f}" if col == "ms / query" else f"{value:.3f}" for col, value in metrics.items()]
        lines.append(f"| {name} | " + " | ".join(cells) + " |")
    lines += [
        "",
        f"Hybrid settings: RRF k = {RRF_K}, weights dense {DENSE_WEIGHT} / keyword {KEYWORD_WEIGHT}, "
        f"{CANDIDATES} candidates from each retriever.",
        f"Generated by `python -m eval.retrieval_eval` on {date.today().isoformat()}.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    questions = load_questions(args.limit)
    print(f"{len(questions)} questions, top {TOP_K} per question")

    results = {}
    with db.get_conn() as conn:
        dense_search(conn, "warm-up", 1)  # the first call loads the embedding model; keep that out of the timings
        for name, search in CONFIGS.items():
            results[name] = evaluate(conn, search, questions)
            print(f"  {name}: " + ", ".join(f"{m} {v:.3f}" for m, v in results[name].items()))

    table = to_markdown(results, len(questions), args.env_file or ".env")
    if args.limit:
        print("\n" + table)
        print("(--limit run: nothing saved)")
        return
    RESULTS_PATH.parent.mkdir(parents=True, exist_ok=True)
    RESULTS_PATH.write_text(table, encoding="utf-8")
    print(f"Saved {RESULTS_PATH}")


if __name__ == "__main__":
    main()
